bool RegisterVextEnums(lua_State* L) {
    int registered = 0;
    for (const EnumChunk& chunk : kEnumChunks) {
        if (luaL_loadbufferx(L, chunk.source, chunk.sourceLen, chunk.chunkName,
                             "t") != LUA_OK) {
            const char* err = lua_tostring(L, -1);
            LogPrintf("ERR ", "VextEnums: не собрался %s: %s", chunk.chunkName,
                      err != nullptr ? err : "?");
            lua_pop(L, 1);
            return false;
        }
        if (lua_pcall(L, 0, 0, 0) != LUA_OK) {
            const char* err = lua_tostring(L, -1);
            LogPrintf("ERR ", "VextEnums: не выполнился %s: %s", chunk.chunkName,
                      err != nullptr ? err : "?");
            lua_pop(L, 1);
            return false;
        }
        ++registered;
    }
    LogPrintf("INFO", "VextEnums: зарегистрировано таблиц-перечислений: %d/%d",
              registered,
              static_cast<int>(sizeof(kEnumChunks) / sizeof(kEnumChunks[0])));
    return true;
}

